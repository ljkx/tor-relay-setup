func obfs4Config() Config {
	c := baseConfig()
	c.Mode = ModeBridge
	c.ORPort = 9443
	c.Bridge = Bridge{Transport: TransportObfs4, Plugin: Obfs4ProxyPath, Port: 8443, Distribution: "any"}
	return c
}

func webTunnelConfig() Config {
	c := baseConfig()
	c.Mode = ModeBridge
	c.Bridge = Bridge{
		Transport: TransportWebTunnel, Plugin: WebTunnelPath, Port: DefaultWebTunnelPort,
		Distribution: "https", URL: "https://bridge.example.org/Abc123secretPath",
	}
	return c
}

// The bridge blocks follow the Tor Project's guides line for line; both
// renders were accepted by tor 0.4.9.13 --verify-config (obfs4 and WebTunnel
// also ran with the real lyrebird/obfs4proxy and webtunnel-server binaries).
func TestRenderObfs4BridgeExact(t *testing.T) {
	c := obfs4Config()
	c.IPv6Address = "2001:db8::5"
	c.Sandbox = true // ignored: tor refuses transports with Sandbox 1
	got := string(c.Render("trs", testNow))
	want := `# Generated by trs on 2026-10-01 12:30:05 UTC.
# Tor relay configuration.
# Review Tor Project relay documentation before making manual changes.

Nickname MyRelay01
ContactInfo "email:ops[]example.org ciissversion:3"

# Bridge mode: unlisted entry point for users in censored networks.
BridgeRelay 1
ORPort 9443
ORPort [2001:db8::5]:9443
ServerTransportPlugin obfs4 exec /usr/bin/obfs4proxy
ServerTransportListenAddr obfs4 0.0.0.0:8443
# Local link between tor and the transport. Always auto.
ExtORPort auto
BridgeDistribution any

# Disable local SOCKS listener on this relay-only server.
SocksPort 0

# Keep potentially sensitive log details scrubbed.
SafeLogging 1
`
	if got != want {
		t.Fatalf("Render mismatch\n--- got ---\n%s--- want ---\n%s", got, want)
	}
}

